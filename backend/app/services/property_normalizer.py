def normalize_property_type(property_type: str | None) -> str | None:
    """property_type → property_category 정규화.

    Returns:
        정규화된 카테고리 문자열, 또는 None (자동차/빈값 등 숨김 대상)
    """
    if property_type is None:
        return None
    pt = property_type.strip()

    # 1. 정확 매칭
    if pt in _EXACT:
        return _EXACT[pt]

    # 2. 부분 매칭
    for keyword, category in _PARTIAL:
        if keyword in pt:
            return category

    return "기타"


